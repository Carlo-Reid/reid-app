-- =====================================================================
-- Improvement 8: when something breaks on someone's screen, the app shows "Something went wrong · Try again"
-- instead of a stuck page, and writes down what broke here so the owner can see it (App errors page).
-- Only the error text, the page and the browser are kept, never customer data; kept 90 days; at most 60 an hour per person.
-- Safe to run more than once.
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.client_errors (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at timestamptz NOT NULL DEFAULT now(),
  app_user_id bigint,
  role text,
  page text,
  message text,
  stack text,
  url text,
  ua text,
  version text);
CREATE INDEX IF NOT EXISTS client_errors_at_idx ON public.client_errors (at DESC);
ALTER TABLE public.client_errors ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.client_errors FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.log_client_error(p_message text, p_stack text DEFAULT NULL, p_page text DEFAULT NULL, p_url text DEFAULT NULL, p_ua text DEFAULT NULL, p_version text DEFAULT NULL)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE me bigint := public.current_app_user_id(); r text := public.current_staff_role();
BEGIN
  IF r IS NULL THEN RETURN false; END IF;
  IF (SELECT count(*) FROM client_errors WHERE app_user_id IS NOT DISTINCT FROM me AND at > now() - interval '1 hour') >= 60 THEN RETURN false; END IF;
  INSERT INTO client_errors (app_user_id, role, page, message, stack, url, ua, version)
  VALUES (me, r, left(p_page, 100), left(coalesce(p_message, '(no message)'), 1000), left(p_stack, 4000),
          left(regexp_replace(coalesce(p_url, ''), '[?].*$', ''), 300), left(p_ua, 300), left(p_version, 40));
  IF random() < 0.02 THEN DELETE FROM client_errors WHERE at < now() - interval '90 days'; END IF;
  RETURN true;
END $$;

CREATE OR REPLACE FUNCTION public.client_error_list(p_days integer DEFAULT 7)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v jsonb; since timestamptz := now() - make_interval(days => least(greatest(coalesce(p_days, 7), 1), 90));
BEGIN
  IF NOT coalesce(public._is_owner(), false) THEN RETURN NULL; END IF;
  WITH e AS (SELECT x.*, nullif(concat_ws(' ', em.first_name, em.last_name), '') AS who
             FROM client_errors x LEFT JOIN app_users u ON u.id = x.app_user_id LEFT JOIN employees em ON em.id = u.employee_id WHERE x.at >= since)
  SELECT jsonb_build_object(
    'n', (SELECT count(*) FROM e),
    'groups', coalesce((SELECT jsonb_agg(g ORDER BY (g->>'last') DESC) FROM (
        SELECT jsonb_build_object('message', message, 'n', count(*), 'first', min(at), 'last', max(at), 'people', array_agg(DISTINCT coalesce(who, role)),
               'pages', array_agg(DISTINCT page), 'stack', (array_agg(stack ORDER BY at DESC))[1], 'version', (array_agg(version ORDER BY at DESC))[1]) g
        FROM e GROUP BY message ORDER BY max(at) DESC LIMIT 200) y), '[]'))
  INTO v;
  RETURN v;
END $$;

REVOKE EXECUTE ON FUNCTION public.log_client_error(text, text, text, text, text, text), public.client_error_list(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.log_client_error(text, text, text, text, text, text), public.client_error_list(integer) TO authenticated;

